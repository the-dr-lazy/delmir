# Empirical checks: (1) Conv1d export op shapes; (2) does Dropout survive export when module is in train mode; (3) explicit-mask MC dropout.
import sys, os, numpy as np, torch, torch.nn as nn, onnx, onnxruntime as ort
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xres_count import xresnet1d  # noqa  (prints its table on import; harmless)

out = os.path.dirname(os.path.abspath(__file__))
print("torch", torch.__version__, "onnx", onnx.__version__, "ort", ort.__version__)

class Net(nn.Module):
    def __init__(self):
        super().__init__()
        self.body = nn.Sequential(nn.Conv1d(12, 16, 5, padding=2), nn.BatchNorm1d(16), nn.ReLU(), nn.AdaptiveAvgPool1d(1), nn.Flatten())
        self.drop = nn.Dropout(0.5)
        self.fc = nn.Linear(16, 1)
    def forward(self, x):
        return self.fc(self.drop(self.body(x)))

x = torch.randn(1, 12, 1000)
for dynamo in (True, False):
    m = Net().eval()
    m.drop.train()  # only dropout in train mode
    p = os.path.join(out, f"mc_{'dyn' if dynamo else 'ts'}.onnx")
    try:
        torch.onnx.export(m, (x,), p, dynamo=dynamo, external_data=False) if dynamo else torch.onnx.export(m, (x,), p, dynamo=False)
        g = onnx.load(p)
        ops = [n.op_type for n in g.graph.node]
        s = ort.InferenceSession(p, providers=["CPUExecutionProvider"])
        name = s.get_inputs()[0].name
        ys = [float(s.run(None, {name: x.numpy()})[0].ravel()[0]) for _ in range(5)]
        print(f"dynamo={dynamo}: ops={ops}\n  5 ORT runs same input -> {ys}  distinct={len(set(ys))}")
    except Exception as e:
        print(f"dynamo={dynamo}: export failed: {type(e).__name__}: {str(e)[:300]}")

# Explicit-mask MC dropout: mask is a model input, generated by the app.
class MaskNet(Net):
    def forward(self, x, mask):
        return self.fc(self.body(x) * mask * 2.0)  # 1/(1-p), p=0.5
m = MaskNet().eval()
p = os.path.join(out, "mc_mask.onnx")
torch.onnx.export(m, (x, torch.ones(1, 16)), p, dynamo=True, external_data=False)
s = ort.InferenceSession(p, providers=["CPUExecutionProvider"])
rng = np.random.default_rng(0)
ys = [float(s.run(None, {"x": x.numpy(), "mask": (rng.random((1, 16)) > 0.5).astype(np.float32)})[0].ravel()[0]) for _ in range(5)]
print("explicit mask:", [n.op_type for n in onnx.load(p).graph.node], ys)

# Conv1d in exported xresnet1d101 graph: check the Conv node input rank
m = xresnet1d(4, [3, 4, 23, 3], lin_ftrs=[128], n_out=4).eval()
p = os.path.join(out, "xres101.onnx")
torch.onnx.export(m, (torch.randn(1, 12, 1000),), p, dynamo=True, external_data=False)
g = onnx.load(p)
from collections import Counter
print("xres101 op counts:", Counter(n.op_type for n in g.graph.node))
print("onnx file size MB:", round(os.path.getsize(p)/1e6, 2), "opset:", [o.version for o in g.opset_import])
conv = next(n for n in g.graph.node if n.op_type == "Conv")
print("first Conv attrs:", [(a.name, onnx.helper.get_attribute_value(a)) for a in conv.attribute])

# Dynamic int8 vs static QDQ quick size check
from onnxruntime.quantization import quantize_dynamic, quantize_static, QuantFormat, QuantType, CalibrationDataReader
class R(CalibrationDataReader):
    def __init__(self): self.it = iter([{"x": np.random.randn(1, 12, 1000).astype(np.float32)} for _ in range(8)])
    def get_next(self): return next(self.it, None)
inp = s2 = ort.InferenceSession(p).get_inputs()[0].name
class R2(CalibrationDataReader):
    def __init__(self): self.it = iter([{inp: np.random.randn(1, 12, 1000).astype(np.float32)} for _ in range(8)])
    def get_next(self): return next(self.it, None)
try:
    quantize_static(p, p.replace(".onnx", "_qdq.onnx"), R2(), quant_format=QuantFormat.QDQ, per_channel=True, weight_type=QuantType.QInt8, activation_type=QuantType.QInt8)
    q = p.replace(".onnx", "_qdq.onnx")
    print("static QDQ size MB:", round(os.path.getsize(q)/1e6, 2))
    a = ort.InferenceSession(p).run(None, {inp: np.ones((1, 12, 1000), np.float32)})[0]
    b = ort.InferenceSession(q).run(None, {inp: np.ones((1, 12, 1000), np.float32)})[0]
    print("fp32 vs qdq logits:", a.ravel(), b.ravel())
except Exception as e:
    print("quantize_static failed:", type(e).__name__, str(e)[:300])

# CPU latency on this desktop (NOT a phone) for scale
import time
for L in (250, 1000, 5000):
    mm = xresnet1d(4, [3, 4, 23, 3], lin_ftrs=[128], n_out=4).eval()
    pp = os.path.join(out, f"xres101_{L}.onnx")
    torch.onnx.export(mm, (torch.randn(1, 12, L),), pp, dynamo=True, external_data=False)
    so = ort.SessionOptions(); so.intra_op_num_threads = 1
    ss = ort.InferenceSession(pp, so, providers=["CPUExecutionProvider"])
    nm = ss.get_inputs()[0].name; xi = np.random.randn(1, 12, L).astype(np.float32)
    for _ in range(3): ss.run(None, {nm: xi})
    t = time.perf_counter(); n = 20
    for _ in range(n): ss.run(None, {nm: xi})
    print(f"desktop ORT CPU 1-thread xres101 L={L}: {(time.perf_counter()-t)/n*1000:.1f} ms/forward")
